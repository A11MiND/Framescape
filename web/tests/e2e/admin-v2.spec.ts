import { test, expect } from '@playwright/test'
import { useDemoApi } from './demo'

for (const lang of ['zh', 'en'] as const)
  test(`${lang}: changing the trend range preserves cumulative KPIs`, async ({ page }) => {
    await useDemoApi(page, { lang })
    await page.goto('/admin/spend')
    await expect(page.getByRole('heading', { name: lang === 'zh' ? '费用' : 'Spend', exact: true })).toBeVisible()
    const cost = page
      .getByText(lang === 'zh' ? '实际费用（人民币）' : 'Actual cost (CNY)', { exact: true })
      .first()
      .locator('..')
    await expect(cost).toContainText('246.80')
    await expect(page.getByRole('row')).toHaveCount(8)
    await page.getByRole('radio', { name: lang === 'zh' ? '30 天' : '30 days', exact: true }).click()
    await expect(page.getByRole('row')).toHaveCount(31)
    await expect(cost).toContainText('246.80')
    await expect(page.getByText(lang === 'zh' ? '已完成' : 'Completed', { exact: true })).toBeVisible()
  })
test('admin mutations name the target and require confirmation', async ({ page }) => {
  await useDemoApi(page)
  await page.goto('/admin/users')
  let posts = 0
  page.on('request', (r) => {
    if (r.method() === 'POST' && r.url().includes('/admin/users/')) posts++
  })
  await page.getByRole('button', { name: '管理 creator1@example.com' }).click()
  await page.getByRole('menuitem', { name: '设为管理员', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toContainText('creator1@example.com')
  await expect(dialog).toContainText('管理所有用户')
  expect(posts).toBe(0)
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  expect(posts).toBe(0)
  await page.getByRole('button', { name: '管理 creator1@example.com' }).click()
  await page.getByRole('menuitem', { name: '停用账号' }).click()
  await page.getByRole('dialog').getByRole('button', { name: '确认修改' }).click()
  await expect(page.getByRole('row').filter({ hasText: 'creator1@example.com' })).toContainText('已停用')
  expect(posts).toBe(1)
})
