test('temporary password exists only in the account creation result', async ({ page }) => {
  await useDemoApi(page)
  await page.goto('/admin/users')
  await page.getByRole('button', { name: '新建账号', exact: true }).click()
  const d = page.getByRole('dialog')
  await d.getByLabel('邮箱').fill('new@example.com')
  await d.getByRole('button', { name: '新建账号', exact: true }).click()
  await expect(d.getByLabel('临时密码')).toHaveValue('demo-temporary-9R!')
  await expect(d).toContainText('只显示这一次')
  await d.getByRole('button', { name: '我已保存，关闭' }).click()
  await expect(page.locator('input[value="demo-temporary-9R!"]')).toHaveCount(0)
  await page.getByRole('button', { name: '新建账号', exact: true }).click()
  await expect(page.getByLabel('临时密码')).toHaveCount(0)
})
test('search and pagination do not silently omit later users', async ({ page }) => {
  await useDemoApi(page)
  await page.goto('/admin/users')
  await expect(page.getByRole('row')).toHaveCount(26)
  await page.getByRole('button', { name: '加载更多用户' }).click()
  await expect(page.getByRole('row')).toHaveCount(29)
  await page.getByRole('textbox', { name: '搜索邮箱或手机' }).fill('creator27')
  await expect(page.getByRole('row')).toHaveCount(2)
  await expect(page.getByRole('row').last()).toContainText('creator27@example.com')
})
test('loading and failed admin data are visible and retryable', async ({ page }) => {
  await useDemoApi(page)
  let fail = true
  await page.route('**/api/v1/admin/users?**', (r) => (fail ? r.fulfill({ status: 500, json: { code: 'internal' } }) : r.fallback()))
  await page.goto('/admin/users')
  await expect(page.getByRole('button', { name: '重试' })).toBeVisible({ timeout: 15000 })
  fail = false
  await page.getByRole('button', { name: '重试' }).click()
  await expect(page.getByRole('row')).toHaveCount(26)
})
test('non-admin accounts cannot enter the admin shell', async ({ page }) => {
  await useDemoApi(page)
  await page.route('**/api/v1/me', (r) => r.fulfill({ json: { biz_id: 'member', is_admin: false, balance: 0, held: 0, entitlements: [] } }))
  await page.goto('/admin/users')
  await expect(page).not.toHaveURL(/admin/)
})
